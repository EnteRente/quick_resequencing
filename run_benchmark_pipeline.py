def resolve_repo_path(path: Path) -> Path:
    return path if path.is_absolute() else (REPO_ROOT / path).resolve()


def format_version(version: Sequence[int]) -> str:
    return ".".join(str(part) for part in version)


def parse_semver(text: str, pattern: str) -> tuple[int, int, int]:
    match = re.search(pattern, text)
    if not match:
        raise RuntimeError(f"Could not parse version from: {text.strip()}")
    return tuple(int(match.group(index)) for index in range(1, 4))


def run_command(
    command: Sequence[Union[str, os.PathLike[str]]],
    *,
    cwd: Path = REPO_ROOT,
    capture_output: bool = False,
    env: Optional[dict[str, str]] = None,
) -> subprocess.CompletedProcess[str]:
    display = " ".join(shlex.quote(os.fspath(part)) for part in command)
    print(f"[run] {display}")
    command_env = os.environ.copy()
    if env:
        command_env.update(env)
    return subprocess.run(
        [os.fspath(part) for part in command],
        cwd=cwd,
        check=True,
        text=True,
        capture_output=capture_output,
        env=command_env,
    )


def running_in_nix_shell() -> bool:
    return (
        os.environ.get(NIX_DEV_ENV_VAR) == "1"
        or bool(os.environ.get("IN_NIX_SHELL"))
    )


def ensure_nix_dev_shell(args: argparse.Namespace) -> None:
    if args.no_nix or running_in_nix_shell():
        return

    if not FLAKE_FILE_PATH.exists():
        raise FileNotFoundError(f"Nix flake not found: {FLAKE_FILE_PATH}")

    nix_executable = shutil.which("nix")
    if nix_executable is None:
        raise RuntimeError(
            "This pipeline is configured to run through the Nix dev shell, but 'nix' "
            "was not found in PATH. Install Nix, or rerun with --no-nix if your "
            "current environment already provides Python/matplotlib, rustc, and cargo."
        )

    command = [
        nix_executable,
        "develop",
        os.fspath(REPO_ROOT),
        "-c",
        "python3",
        os.fspath(PIPELINE_FILE_PATH),
        "--no-nix",
        *sys.argv[1:],
    ]
    display = " ".join(shlex.quote(part) for part in command)
    print(f"[info] Re-entering pipeline through Nix dev shell: {display}")
    completed = subprocess.run(command, cwd=REPO_ROOT)
    raise SystemExit(completed.returncode)


def verify_python_version() -> tuple[int, int, int]:
    current = sys.version_info[:3]
    if current < MIN_PYTHON:
        raise RuntimeError(
            f"Python {format_version(MIN_PYTHON)} or newer is required; "
            f"found {format_version(current)}."
        )
    return current


def verify_python_dependencies(*, skip_plot: bool) -> None:
    if skip_plot:
        return

    if importlib.util.find_spec("matplotlib") is None:
        raise RuntimeError(
            "Python package 'matplotlib' is not available in the active environment. "
            "Enter the Nix dev shell with 'nix develop' and rerun the pipeline."
        )


def verify_rust_toolchain() -> tuple[str, str]:
    rustc = run_command(["rustc", "--version"], capture_output=True).stdout.strip()
    cargo = run_command(["cargo", "--version"], capture_output=True).stdout.strip()
    rustc_version = parse_semver(rustc, r"rustc (\d+)\.(\d+)\.(\d+)")
    if rustc_version < MIN_RUST:
        raise RuntimeError(
            f"Rust {format_version(MIN_RUST)} or newer is required for edition 2024; "
            f"found {format_version(rustc_version)}."
        )
    return rustc, cargo


def verify_perf_support(perf_mode: str, sudo_perf: bool) -> None:
    if perf_mode == "none":
        return

    if sys.platform != "linux":
        raise RuntimeError("Linux perf integration is only supported when this script runs on Linux.")

    perf_check = shutil.which("perf")
    if perf_check is None:
        raise RuntimeError("perf was requested, but the 'perf' executable was not found in PATH.")

    if sudo_perf and not running_as_root() and shutil.which("sudo") is None:
        raise RuntimeError("--sudo-perf was requested, but the 'sudo' executable was not found in PATH.")


def running_as_root() -> bool:
    return hasattr(os, "geteuid") and os.geteuid() == 0


def perf_executable() -> str:
    return shutil.which("perf") or "perf"


def perf_command_prefix(sudo_perf: bool, env: dict[str, str]) -> list[str]:
    if not sudo_perf or running_as_root():
        return [perf_executable()]

    command = ["sudo"]
    if env:
        preserved_env = ",".join(sorted(env))
        command.append(f"--preserve-env={preserved_env}")
    command.append(perf_executable())
    return command


def normalize_selected_schemes(raw_schemes: Sequence[str]) -> list[str]:
    if not raw_schemes:
        return []

    selected: list[str] = []
    for raw_value in raw_schemes:
        for raw_scheme in raw_value.split(","):
            scheme = raw_scheme.strip()
            if not scheme:
                continue

            key = scheme.replace("-", "_").lower()
            if key == "all":
                return []

            canonical = SCHEME_ALIASES.get(key)
            if canonical is None:
                allowed = ", ".join(SCHEME_ORDER)
                raise ValueError(f"Unknown scheme '{scheme}'. Supported values: {allowed}")

            if canonical not in selected:
                selected.append(canonical)

    return sorted(selected, key=SCHEME_ORDER.index)


def normalize_selected_implementations(
    raw_implementations: Sequence[str],
    *,
    default_to_all: bool,
) -> list[str]:
    if not raw_implementations:
        return list(IMPLEMENTATION_ORDER) if default_to_all else []

    selected: list[str] = []
    for raw_value in raw_implementations:
        for raw_implementation in raw_value.split(","):
            implementation = raw_implementation.strip()
            if not implementation:
                continue

            key = implementation.replace("-", "_").lower()
            if key == "all":
                return list(IMPLEMENTATION_ORDER)

            canonical = IMPLEMENTATION_ALIASES.get(key)
            if canonical is None:
                allowed = ", ".join(IMPLEMENTATION_ORDER)
                raise ValueError(
                    f"Unknown implementation '{implementation}'. Supported values: {allowed}"
                )

            if canonical not in selected:
                selected.append(canonical)

    if not selected and default_to_all:
        return list(IMPLEMENTATION_ORDER)

    return sorted(selected, key=IMPLEMENTATION_ORDER.index)


def normalize_selected_packet_counts(
    raw_packet_counts: Sequence[str],
    *,
    default_to_all: bool,
) -> list[int]:
    if not raw_packet_counts:
        return list(PACKET_COUNT_ORDER) if default_to_all else []

    selected: list[int] = []
    for raw_value in raw_packet_counts:
        for raw_packet_count in raw_value.split(","):
            packet_count_value = raw_packet_count.strip()
            if not packet_count_value:
                continue

            if packet_count_value.lower() == "all":
                return list(PACKET_COUNT_ORDER)

            try:
                packet_count = int(packet_count_value)
            except ValueError as error:
                raise ValueError(f"Invalid packet count '{packet_count_value}'.") from error

            if packet_count <= 0:
                raise ValueError(f"Packet count must be greater than zero: {packet_count}")

            if packet_count not in selected:
                selected.append(packet_count)

    if not selected and default_to_all:
        return list(PACKET_COUNT_ORDER)

    return sorted(
        selected,
        key=lambda packet_count: (
            PACKET_COUNT_ORDER.index(packet_count)
            if packet_count in PACKET_COUNT_ORDER
            else len(PACKET_COUNT_ORDER),
            packet_count,
        ),
    )


def selected_or_default_schemes(selected_schemes: Sequence[str]) -> list[str]:
    return list(selected_schemes) if selected_schemes else list(SCHEME_ORDER)


def selected_or_default_packet_counts(selected_packet_counts: Sequence[int]) -> list[int]:
    return list(selected_packet_counts) if selected_packet_counts else list(PACKET_COUNT_ORDER)


def packet_counts_for_scheme(scheme: str, packet_counts: Sequence[int]) -> list[int]:
    if scheme == "RandomLossRate":
        return (
            [RANDOM_LOSS_RATE_PACKET_COUNT]
            if RANDOM_LOSS_RATE_PACKET_COUNT in packet_counts
            else []
        )
    return list(packet_counts)


def perf_scenario_matrix(
    implementations: Sequence[str],
    schemes: Sequence[str],
    packet_counts: Sequence[int],
) -> list[tuple[str, str, int]]:
    return [
        (implementation, scheme, packet_count)
        for implementation in implementations
        for scheme in schemes
        for packet_count in packet_counts_for_scheme(scheme, packet_counts)
    ]


def benchmark_env(
    selected_schemes: Sequence[str],
    selected_implementations: Sequence[str] = (),
    selected_packet_counts: Sequence[int] = (),
) -> dict[str, str]:
    env: dict[str, str] = {}
    if selected_schemes:
        env[BENCH_SCHEMES_ENV_VAR] = ",".join(selected_schemes)
    if selected_implementations:
        env[BENCH_IMPLEMENTATIONS_ENV_VAR] = ",".join(selected_implementations)
    if selected_packet_counts:
        env[BENCH_BURST_SIZES_ENV_VAR] = ",".join(str(count) for count in selected_packet_counts)
        env[BENCH_PACKET_COUNTS_ENV_VAR] = ",".join(str(count) for count in selected_packet_counts)
    return env


def split_perf_event_list(raw_value: str) -> list[str]:
    events: list[str] = []
    brace_depth = 0
    in_pmu_config = False
    start = 0

    for index, char in enumerate(raw_value):
        if char == "{":
            brace_depth += 1
        elif char == "}" and brace_depth:
            brace_depth -= 1
        elif char == "/" and brace_depth == 0:
            in_pmu_config = not in_pmu_config
        elif char == "," and brace_depth == 0 and not in_pmu_config:
            events.append(raw_value[start:index])
            start = index + 1

    events.append(raw_value[start:])
    return events


def normalize_perf_events(raw_perf_events: Sequence[Sequence[str]]) -> list[str]:
    events: list[str] = []
    for event_group in raw_perf_events:
        for raw_value in event_group:
            for raw_event in split_perf_event_list(raw_value):
                event = raw_event.strip()
                if event and event not in events:
                    events.append(event)

    return events


def safe_path_component(value: str) -> str:
    safe_value = re.sub(r"[^A-Za-z0-9_.-]+", "_", value).strip("_")
    if not safe_value:
        raise ValueError(f"Cannot derive a filesystem-safe name from: {value!r}")
    return safe_value


def clean_directory(path: Path) -> None:
    if path.exists():
        shutil.rmtree(path)
    path.mkdir(parents=True, exist_ok=True)


def run_benchmark(bench_name: str, env: dict[str, str]) -> None:
    run_command(["cargo", "bench", "--bench", bench_name], env=env)


def build_bench_binary(bench_name: str) -> Path:
    command = [
        "cargo",
        "bench",
        "--bench",
        bench_name,
        "--no-run",
        "--message-format=json",
    ]
    display = " ".join(shlex.quote(part) for part in command)
    print(f"[run] {display}")
    result = subprocess.run(
        command,
        cwd=REPO_ROOT,
        check=True,
        text=True,
        stdout=subprocess.PIPE,
    )

    bench_binary: Optional[Path] = None
    for line in result.stdout.splitlines():
        try:
            message = json.loads(line)
        except json.JSONDecodeError:
            continue

        if message.get("reason") != "compiler-artifact":
            continue
        target = message.get("target") or {}
        target_kinds = target.get("kind") or []
        if target.get("name") != bench_name or "bench" not in target_kinds:
            continue
        executable = message.get("executable")
        if executable:
            bench_binary = Path(executable)

    if bench_binary is None:
        raise RuntimeError(f"Could not determine the built executable for bench target '{bench_name}'.")

    if not bench_binary.exists():
        raise FileNotFoundError(f"Built bench executable not found: {bench_binary}")

    return bench_binary


def git_output(args: Sequence[str]) -> Optional[str]:
    if shutil.which("git") is None:
        return None

    try:
        result = subprocess.run(
            ["git", *args],
            cwd=REPO_ROOT,
            check=True,
            text=True,
            stdout=subprocess.PIPE,
            stderr=subprocess.DEVNULL,
        )
    except (FileNotFoundError, subprocess.CalledProcessError):
        return None

    return result.stdout.strip()


def archive_perf_context(perf_output_dir: Path, bench_binary: Path) -> dict[str, str]:
    context_dir = perf_output_dir / "context"
    context_dir.mkdir(parents=True, exist_ok=True)

    archived_bench_binary = context_dir / bench_binary.name
    shutil.copy2(bench_binary, archived_bench_binary)

    metadata = {
        "archived_bench_binary": f"context/{archived_bench_binary.name}",
    }

    git_commit = git_output(["rev-parse", "HEAD"])
    if git_commit:
        (context_dir / "git_commit.txt").write_text(git_commit + "\n", encoding="utf-8")
        metadata["git_commit"] = git_commit
        metadata["archived_git_commit"] = "context/git_commit.txt"

    git_short_commit = git_output(["rev-parse", "--short", "HEAD"])
    if git_short_commit:
        metadata["git_commit_short"] = git_short_commit

    git_status = git_output(["status", "--short"])
    if git_status is not None:
        status_path = context_dir / "git_status.txt"
        status_path.write_text(
            git_status + ("\n" if git_status else ""),
            encoding="utf-8",
        )
        metadata["git_dirty"] = str(bool(git_status))
        metadata["archived_git_status"] = "context/git_status.txt"

    return metadata


def run_perf_stat(
    bench_binary: Path,
    perf_events: Sequence[str],
    perf_output_dir: Path,
    env: dict[str, str],
    sudo_perf: bool,
    bench_args: Sequence[str] = (),
) -> dict[str, str]:
    perf_command: list[Union[str, os.PathLike[str]]] = perf_command_prefix(sudo_perf, env)
    perf_command.append("stat")
    for event in perf_events:
        perf_command.extend(["-e", event])

    perf_stat_path = perf_output_dir / "perf_stat.txt"
    perf_command.extend(["-d", "-d", "-d", "-o", perf_stat_path, bench_binary, *bench_args])
    run_command(perf_command, env=env)
    return {"perf_stat_path": str(perf_stat_path)}


def run_perf_record(
    bench_binary: Path,
    perf_events: Sequence[str],
    perf_output_dir: Path,
    env: dict[str, str],
    sudo_perf: bool,
    bench_args: Sequence[str] = (),
) -> dict[str, str]:
    perf_command: list[Union[str, os.PathLike[str]]] = perf_command_prefix(sudo_perf, env)
    perf_command.append("record")
    for event in perf_events:
        perf_command.extend(["-e", event])

    perf_data_path = perf_output_dir / "perf.data"
    perf_report_path = perf_output_dir / "perf_report.txt"
    perf_command.extend(["-o", perf_data_path, bench_binary, *bench_args])
    run_command(perf_command, env=env)
    report_command = [perf_executable(), "report", "--stdio", "-i", os.fspath(perf_data_path)]
    display = " ".join(shlex.quote(part) for part in report_command)
    print(f"[run] {display}")
    report_result = subprocess.run(
        report_command,
        cwd=REPO_ROOT,
        check=True,
        text=True,
        stdout=subprocess.PIPE,
    )
    print(report_result.stdout, end="")
    perf_report_path.write_text(report_result.stdout, encoding="utf-8")
    return {
        "perf_data_path": str(perf_data_path),
        "perf_report_path": str(perf_report_path),
    }


def run_perf_benchmark(
    bench_name: str,
    perf_mode: str,
    perf_events: Sequence[str],
    perf_output_dir: Path,
    env: dict[str, str],
    sudo_perf: bool,
    bench_filter: Optional[str] = None,
) -> dict[str, str]:
    bench_binary = build_bench_binary(bench_name)
    clean_directory(perf_output_dir)
    bench_args = [bench_filter] if bench_filter else []

    metadata = {
        "bench_binary": str(bench_binary),
        "perf_mode": perf_mode,
        "sudo_perf": str(sudo_perf),
    }
    metadata.update(archive_perf_context(perf_output_dir, bench_binary))
    if perf_events:
        metadata["perf_events"] = ",".join(perf_events)
    if bench_filter:
        metadata["criterion_filter"] = bench_filter

    if perf_mode in {"stat", "both"}:
        metadata.update(
            run_perf_stat(bench_binary, perf_events, perf_output_dir, env, sudo_perf, bench_args)
        )

    if perf_mode in {"record", "both"}:
        metadata.update(
            run_perf_record(bench_binary, perf_events, perf_output_dir, env, sudo_perf, bench_args)
        )

    return metadata


def run_perf_benchmarks_by_implementation(
    bench_name: str,
    perf_mode: str,
    perf_events: Sequence[str],
    perf_output_dir: Path,
    env: dict[str, str],
    sudo_perf: bool,
    implementations: Sequence[str],
) -> dict[str, str]:
    bench_binary = build_bench_binary(bench_name)
    clean_directory(perf_output_dir)

    metadata = {
        "bench_binary": str(bench_binary),
        "perf_mode": perf_mode,
        "sudo_perf": str(sudo_perf),
        "perf_by_implementation": "true",
        "perf_implementations": ",".join(implementations),
    }
    metadata.update(archive_perf_context(perf_output_dir, bench_binary))
    if perf_events:
        metadata["perf_events"] = ",".join(perf_events)

    result_dirs: list[str] = []
    for implementation in implementations:
        implementation_dir_name = safe_path_component(implementation)
        implementation_dir = perf_output_dir / implementation_dir_name
        implementation_dir.mkdir(parents=True, exist_ok=True)
        bench_args = [implementation]
        implementation_env = dict(env)
        implementation_env[BENCH_IMPLEMENTATIONS_ENV_VAR] = implementation
        result_dirs.append(implementation_dir_name)

        implementation_metadata = dict(metadata)
        implementation_metadata.update(
            {
                "implementation": implementation,
                "criterion_filter": implementation,
                "perf_output_dir": str(implementation_dir),
            }
        )

        if perf_mode in {"stat", "both"}:
            implementation_metadata.update(
                run_perf_stat(
                    bench_binary,
                    perf_events,
                    implementation_dir,
                    implementation_env,
                    sudo_perf,
                    bench_args,
                )
            )

        if perf_mode in {"record", "both"}:
            implementation_metadata.update(
                run_perf_record(
                    bench_binary,
                    perf_events,
                    implementation_dir,
                    implementation_env,
                    sudo_perf,
                    bench_args,
                )
            )

        metadata_path = implementation_dir / "run_metadata.json"
        metadata_path.write_text(
            json.dumps(implementation_metadata, indent=2) + "\n",
            encoding="utf-8",
        )

    metadata["implementation_result_dirs"] = ",".join(result_dirs)
    return metadata


def run_perf_benchmarks_by_scenario(
    bench_name: str,
    perf_mode: str,
    perf_events: Sequence[str],
    perf_output_dir: Path,
    env: dict[str, str],
    sudo_perf: bool,
    implementations: Sequence[str],
    schemes: Sequence[str],
    packet_counts: Sequence[int],
) -> dict[str, str]:
    bench_binary = build_bench_binary(bench_name)
    clean_directory(perf_output_dir)

    metadata = {
        "bench_binary": str(bench_binary),
        "perf_mode": perf_mode,
        "sudo_perf": str(sudo_perf),
        "perf_by_scenario": "true",
        "perf_implementations": ",".join(implementations),
        "perf_schemes": ",".join(schemes),
        "perf_packet_counts": ",".join(str(count) for count in packet_counts),
    }
    metadata.update(archive_perf_context(perf_output_dir, bench_binary))
    if perf_events:
        metadata["perf_events"] = ",".join(perf_events)

    scenario_matrix = perf_scenario_matrix(implementations, schemes, packet_counts)
    if not scenario_matrix:
        raise RuntimeError(
            "No perf scenarios were selected. Check --scheme and --burst-size filters."
        )

    metadata["expected_scenario_count"] = str(len(scenario_matrix))

    index_entries: list[dict[str, str]] = []
    for implementation, scheme, packet_count in scenario_matrix:
        relative_dir = (
            Path(safe_path_component(implementation))
            / safe_path_component(scheme)
            / f"packets_{packet_count}"
        )
        scenario_dir = perf_output_dir / relative_dir
        scenario_dir.mkdir(parents=True, exist_ok=True)

        scenario_env = dict(env)
        scenario_env[BENCH_IMPLEMENTATIONS_ENV_VAR] = implementation
        scenario_env[BENCH_SCHEMES_ENV_VAR] = scheme
        scenario_env[BENCH_BURST_SIZES_ENV_VAR] = str(packet_count)
        scenario_env[BENCH_PACKET_COUNTS_ENV_VAR] = str(packet_count)
        bench_args = [implementation]

        scenario_metadata = dict(metadata)
        scenario_metadata.update(
            {
                "implementation": implementation,
                "scheme": scheme,
                "packet_count": str(packet_count),
                "criterion_filter": implementation,
                "perf_output_dir": str(scenario_dir),
            }
        )

        if perf_mode in {"stat", "both"}:
            scenario_metadata.update(
                run_perf_stat(
                    bench_binary,
                    perf_events,
                    scenario_dir,
                    scenario_env,
                    sudo_perf,
                    bench_args,
                )
            )

        if perf_mode in {"record", "both"}:
            scenario_metadata.update(
                run_perf_record(
                    bench_binary,
                    perf_events,
                    scenario_dir,
                    scenario_env,
                    sudo_perf,
                    bench_args,
                )
            )

        metadata_path = scenario_dir / "run_metadata.json"
        metadata_path.write_text(
            json.dumps(scenario_metadata, indent=2) + "\n",
            encoding="utf-8",
        )

        index_entry = {
            "implementation": implementation,
            "scheme": scheme,
            "packet_count": str(packet_count),
            "result_dir": os.fspath(relative_dir),
        }
        if perf_mode in {"stat", "both"}:
            index_entry["perf_stat_path"] = os.fspath(relative_dir / "perf_stat.txt")
        if perf_mode in {"record", "both"}:
            index_entry["perf_data_path"] = os.fspath(relative_dir / "perf.data")
            index_entry["perf_report_path"] = os.fspath(relative_dir / "perf_report.txt")
        index_entries.append(index_entry)

    (perf_output_dir / "perf_index.json").write_text(
        json.dumps(index_entries, indent=2) + "\n",
        encoding="utf-8",
    )
    metadata["scenario_count"] = str(len(index_entries))
    metadata["archived_perf_index"] = "perf_index.json"
    return metadata


def run_plotter(
    python_executable: Path,
    criterion_root: Path,
    plot_output_dir: Path,
    group: str,
    selected_schemes: Sequence[str],
    selected_implementations: Sequence[str],
    selected_packet_counts: Sequence[int],
) -> None:
    plotter_path = PLOTTER_FILE_PATH
    if not plotter_path.exists():
        raise FileNotFoundError(f"Plotter script not found: {PLOTTER_FILE_PATH}")

    if not criterion_root.exists():
        raise FileNotFoundError(f"Criterion output directory not found: {criterion_root}")

    clean_directory(plot_output_dir)
    command: list[Union[str, os.PathLike[str]]] = [
        python_executable,
        plotter_path,
        "--criterion-root",
        criterion_root,
        "--output-dir",
        plot_output_dir,
        "--group",
        group,
    ]
    for scheme in selected_schemes:
        command.extend(["--scheme", scheme])
    for implementation in selected_implementations:
        command.extend(["--implementation", implementation])
    for packet_count in selected_packet_counts:
        command.extend(["--packet-count", str(packet_count)])

    run_command(command)


def collect_plot_files(plot_output_dir: Path) -> list[Path]:
    if not plot_output_dir.exists():
        raise FileNotFoundError(f"Plot output directory not found: {plot_output_dir}")

    plots = sorted(plot_output_dir.glob("*.png"))
    if not plots:
        raise RuntimeError(f"No plot PNG files found in {plot_output_dir}")
    return plots


def publish_plots(
    plot_output_dir: Path,
    publish_dir: Path,
    metadata: dict[str, str],
    timestamp: str,
) -> tuple[Path, Path]:
    runs_dir = publish_dir / "plots" / "runs"
    latest_dir = publish_dir / "plots" / "latest"
    run_dir = runs_dir / timestamp

    run_dir.parent.mkdir(parents=True, exist_ok=True)
    shutil.copytree(plot_output_dir, run_dir)

    if latest_dir.exists():
        shutil.rmtree(latest_dir)
    shutil.copytree(plot_output_dir, latest_dir)

    for target_dir in (run_dir, latest_dir):
        metadata_path = target_dir / "run_metadata.json"
        metadata_path.write_text(json.dumps(metadata, indent=2) + "\n", encoding="utf-8")

    return run_dir, latest_dir


def publish_perf_artifacts(
    perf_output_dir: Path,
    publish_dir: Path,
    metadata: dict[str, str],
    timestamp: str,
) -> tuple[Path, Path]:
    runs_dir = publish_dir / "perf" / "runs"
    latest_dir = publish_dir / "perf" / "latest"
    run_dir = runs_dir / timestamp

    run_dir.parent.mkdir(parents=True, exist_ok=True)
    shutil.copytree(perf_output_dir, run_dir)

    if latest_dir.exists():
        shutil.rmtree(latest_dir)
    shutil.copytree(perf_output_dir, latest_dir)

    for target_dir in (run_dir, latest_dir):
        target_metadata = dict(metadata)

        if (target_dir / "perf.data").exists():
            target_metadata["archived_perf_data"] = str(target_dir / "perf.data")
        if (target_dir / "perf_report.txt").exists():
            target_metadata["archived_perf_report"] = str(target_dir / "perf_report.txt")
        if (target_dir / "perf_stat.txt").exists():
            target_metadata["archived_perf_stat"] = str(target_dir / "perf_stat.txt")

        archived_bench_binary = target_dir / "context" / Path(metadata["archived_bench_binary"]).name
        if archived_bench_binary.exists():
            target_metadata["archived_bench_binary"] = str(archived_bench_binary)

        archived_git_commit = target_dir / "context" / "git_commit.txt"
        if archived_git_commit.exists():
            target_metadata["archived_git_commit"] = str(archived_git_commit)

        archived_git_status = target_dir / "context" / "git_status.txt"
        if archived_git_status.exists():
            target_metadata["archived_git_status"] = str(archived_git_status)

        metadata_path = target_dir / "run_metadata.json"
        metadata_path.write_text(json.dumps(target_metadata, indent=2) + "\n", encoding="utf-8")

    return run_dir, latest_dir


def main() -> int:
    args = parse_args()
    ensure_nix_dev_shell(args)

    criterion_root = resolve_repo_path(args.criterion_root)
    plot_output_dir = resolve_repo_path(args.plot_output_dir)
    perf_output_dir = resolve_repo_path(args.perf_output_dir)
    publish_dir = resolve_repo_path(args.publish_dir)
    python_executable = Path(sys.executable).resolve()
    selected_schemes = normalize_selected_schemes(args.scheme)
    perf_events = normalize_perf_events(args.perf_events)
    selected_implementations = normalize_selected_implementations(
        args.implementation,
        default_to_all=args.perf_by_implementation or args.perf_by_scenario,
    )
    selected_packet_counts = normalize_selected_packet_counts(
        args.packet_counts,
        default_to_all=args.perf_by_scenario,
    )
    selected_benchmark_env = benchmark_env(
        selected_schemes,
        selected_implementations if not args.perf_by_scenario else [],
        selected_packet_counts if not args.perf_by_scenario else [],
    )
    timestamp = datetime.now().strftime("%Y%m%d_%H%M%S")

    if args.perf == "none" and (args.perf_by_implementation or args.perf_by_scenario):
        raise RuntimeError("--perf-by-implementation/--perf-by-scenario requires --perf stat, record, or both.")

    python_version = verify_python_version()
    verify_python_dependencies(skip_plot=args.skip_plot)
    rustc_version, cargo_version = verify_rust_toolchain()
    verify_perf_support(args.perf, args.sudo_perf)

    print(
        "[info] Toolchain OK: "
        f"python={format_version(python_version)} "
        f"rustc={rustc_version} "
        f"cargo={cargo_version}"
    )

    perf_metadata: dict[str, str] = {}
    if not args.skip_bench:
        if args.perf == "none":
            run_benchmark(args.bench_name, selected_benchmark_env)
        elif args.perf_by_scenario:
            perf_metadata = run_perf_benchmarks_by_scenario(
                args.bench_name,
                args.perf,
                perf_events,
                perf_output_dir,
                benchmark_env(()),
                args.sudo_perf,
                selected_implementations,
                selected_or_default_schemes(selected_schemes),
                selected_or_default_packet_counts(selected_packet_counts),
            )
        elif args.perf_by_implementation or selected_implementations:
            perf_metadata = run_perf_benchmarks_by_implementation(
                args.bench_name,
                args.perf,
                perf_events,
                perf_output_dir,
                selected_benchmark_env,
                args.sudo_perf,
                selected_implementations,
            )
        else:
            perf_metadata = run_perf_benchmark(
                args.bench_name,
                args.perf,
                perf_events,
                perf_output_dir,
                selected_benchmark_env,
                args.sudo_perf,
            )

    if not args.skip_plot:
        run_plotter(
            python_executable,
            criterion_root,
            plot_output_dir,
            args.group,
            selected_schemes,
            selected_implementations,
            selected_packet_counts,
        )

    plots = collect_plot_files(plot_output_dir)
    metadata = {
        "generated_at": datetime.now().isoformat(timespec="seconds"),
        "repo_root": str(REPO_ROOT),
        "python_executable": str(python_executable),
        "python_version": format_version(python_version),
        "rustc_version": rustc_version,
        "cargo_version": cargo_version,
        "bench_name": args.bench_name,
        "selected_schemes": ",".join(selected_schemes) if selected_schemes else "all",
        "selected_implementations": (
            ",".join(selected_implementations) if selected_implementations else "aggregate"
        ),
        "selected_packet_counts": (
            ",".join(str(count) for count in selected_packet_counts)
            if selected_packet_counts
            else "all"
        ),
        "criterion_root": str(criterion_root),
        "plot_output_dir": str(plot_output_dir),
        "plot_count": str(len(plots)),
        "plot_files": ",".join(plot.name for plot in plots),
        "perf_mode": args.perf,
    }
    metadata.update(perf_metadata)
    run_dir, latest_dir = publish_plots(plot_output_dir, publish_dir, metadata, timestamp)

    print("[done] Published plots:")
    print(f"  latest: {latest_dir}")
    print(f"  archived: {run_dir}")
    if args.perf != "none" and perf_output_dir.exists():
        perf_run_dir, perf_latest_dir = publish_perf_artifacts(
            perf_output_dir,
            publish_dir,
            metadata,
            timestamp,
        )
        print("[done] Published perf artifacts:")
        print(f"  latest: {perf_latest_dir}")
        print(f"  archived: {perf_run_dir}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
