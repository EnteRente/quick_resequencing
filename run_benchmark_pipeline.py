#!/usr/bin/env python3

from __future__ import annotations

import argparse
import json
import importlib.util
import os
import re
import shlex
import shutil
import subprocess
import sys
from datetime import datetime
from pathlib import Path
from typing import Optional, Sequence, Union

REPO_ROOT = Path(__file__).resolve().parent
BENCH_RES_DIR_PATH = REPO_ROOT / "benchmark_results"
FLAKE_FILE_PATH = REPO_ROOT / "flake.nix"
PLOTTER_FILE_PATH = REPO_ROOT / "box_plotter.py"
PIPELINE_FILE_PATH = REPO_ROOT / "run_benchmark_pipeline.py"
NIX_DEV_ENV_VAR = "QUICK_RESEQUENCING_NIX_DEV"
BENCH_SCHEMES_ENV_VAR = "QUICK_RESEQUENCING_SCHEMES"
SCHEME_ORDER = ["InOrder", "FirstToLast", "RandomLoss"]
SCHEME_ALIASES = {
    "inorder": "InOrder",
    "in_order": "InOrder",
    "firsttolast": "FirstToLast",
    "first_to_last": "FirstToLast",
    "randomloss": "RandomLoss",
    "random_loss": "RandomLoss",
    "randomlossrate": "RandomLoss",
    "random_loss_rate": "RandomLoss",
}
MIN_PYTHON = (3, 9, 0)
MIN_RUST = (1, 85, 0)


def parse_args() -> argparse.Namespace:
    parser = argparse.ArgumentParser(
        description=(
            "Enter the Nix dev shell when needed, verify the toolchain, run the "
            "Criterion benchmark, generate the box plots, and publish them to "
            "{} folder.".format(BENCH_RES_DIR_PATH)
        )
    )
    parser.add_argument(
        "--bench-name",
        default="resequencing_bench",
        help="Cargo bench target to run.",
    )
    parser.add_argument(
        "--criterion-root",
        type=Path,
        default=Path("target/criterion"),
        help="Criterion output directory generated by cargo bench.",
    )
    parser.add_argument(
        "--plot-output-dir",
        type=Path,
        default=Path("target/criterion_packet_boxplots"),
        help=f"Intermediate directory where {PLOTTER_FILE_PATH} writes the plot PNG files.",
    )
    parser.add_argument(
        "--publish-dir",
        type=Path,
        default=Path("benchmark_results"),
        help="Stable repo-root folder where the generated plots are copied.",
    )
    parser.add_argument(
        "--group",
        default="Comparison of Resequencing Data Structures",
        help=f"Criterion benchmark group passed to {PLOTTER_FILE_PATH}.",
    )
    parser.add_argument(
        "--scheme",
        action="append",
        default=[],
        help=(
            "Only benchmark and plot the given scheme. Repeat this option or use a "
            "comma-separated list. Supported values: InOrder, FirstToLast, RandomLoss."
        ),
    )
    parser.add_argument(
        "--perf",
        choices=["none", "stat", "record", "both"],
        default="none",
        help=(
            "Run the bench binary under Linux perf. "
            "'stat' writes summary counters, 'record' writes perf.data plus a text report, "
            "'both' runs stat first and record second."
        ),
    )
    parser.add_argument(
        "--perf-events",
        default="",
        help="Optional comma-separated perf event list passed via 'perf -e'.",
    )
    parser.add_argument(
        "--sudo-perf",
        action="store_true",
        help="Prefix only the perf stat/record command with sudo; do not run the whole pipeline as root.",
    )
    parser.add_argument(
        "--perf-output-dir",
        type=Path,
        default=Path("target/perf_artifacts"),
        help="Intermediate directory used for raw perf output before publishing.",
    )
    parser.add_argument(
        "--skip-bench",
        action="store_true",
        help="Skip cargo bench and only re-render plots from existing Criterion output.",
    )
    parser.add_argument(
        "--skip-plot",
        action="store_true",
        help=f"Skip running {PLOTTER_FILE_PATH} and only publish existing plot files.",
    )
    parser.add_argument(
        "--no-nix",
        action="store_true",
        help="Do not auto-enter the Nix dev shell; use the current environment as-is.",
    )
    return parser.parse_args()


def resolve_repo_path(path: Path) -> Path:
    return path if path.is_absolute() else (REPO_ROOT / path).resolve()


def format_version(version: Sequence[int]) -> str:
    return ".".join(str(part) for part in version)


def parse_semver(text: str, pattern: str) -> tuple[int, int, int]:
    match = re.search(pattern, text)
    if not match:
        raise RuntimeError(f"Could not parse version from: {text.strip()}")
    return tuple(int(match.group(index)) for index in range(1, 4))


def run_command(
    command: Sequence[Union[str, os.PathLike[str]]],
    *,
    cwd: Path = REPO_ROOT,
    capture_output: bool = False,
    env: Optional[dict[str, str]] = None,
) -> subprocess.CompletedProcess[str]:
    display = " ".join(shlex.quote(os.fspath(part)) for part in command)
    print(f"[run] {display}")
    command_env = os.environ.copy()
    if env:
        command_env.update(env)
    return subprocess.run(
        [os.fspath(part) for part in command],
        cwd=cwd,
        check=True,
        text=True,
        capture_output=capture_output,
        env=command_env,
    )


def running_in_nix_shell() -> bool:
    return (
        os.environ.get(NIX_DEV_ENV_VAR) == "1"
        or bool(os.environ.get("IN_NIX_SHELL"))
    )


def ensure_nix_dev_shell(args: argparse.Namespace) -> None:
    if args.no_nix or running_in_nix_shell():
        return

    if not FLAKE_FILE_PATH.exists():
        raise FileNotFoundError(f"Nix flake not found: {FLAKE_FILE_PATH}")

    nix_executable = shutil.which("nix")
    if nix_executable is None:
        raise RuntimeError(
            "This pipeline is configured to run through the Nix dev shell, but 'nix' "
            "was not found in PATH. Install Nix, or rerun with --no-nix if your "
            "current environment already provides Python/matplotlib, rustc, and cargo."
        )

    command = [
        nix_executable,
        "develop",
        os.fspath(REPO_ROOT),
        "-c",
        "python3",
        os.fspath(PIPELINE_FILE_PATH),
        "--no-nix",
        *sys.argv[1:],
    ]
    display = " ".join(shlex.quote(part) for part in command)
    print(f"[info] Re-entering pipeline through Nix dev shell: {display}")
    completed = subprocess.run(command, cwd=REPO_ROOT)
    raise SystemExit(completed.returncode)


def verify_python_version() -> tuple[int, int, int]:
    current = sys.version_info[:3]
    if current < MIN_PYTHON:
        raise RuntimeError(
            f"Python {format_version(MIN_PYTHON)} or newer is required; "
            f"found {format_version(current)}."
        )
    return current


def verify_python_dependencies(*, skip_plot: bool) -> None:
    if skip_plot:
        return

    if importlib.util.find_spec("matplotlib") is None:
        raise RuntimeError(
            "Python package 'matplotlib' is not available in the active environment. "
            "Enter the Nix dev shell with 'nix develop' and rerun the pipeline."
        )


def verify_rust_toolchain() -> tuple[str, str]:
    rustc = run_command(["rustc", "--version"], capture_output=True).stdout.strip()
    cargo = run_command(["cargo", "--version"], capture_output=True).stdout.strip()
    rustc_version = parse_semver(rustc, r"rustc (\d+)\.(\d+)\.(\d+)")
    if rustc_version < MIN_RUST:
        raise RuntimeError(
            f"Rust {format_version(MIN_RUST)} or newer is required for edition 2024; "
            f"found {format_version(rustc_version)}."
        )
    return rustc, cargo


def verify_perf_support(perf_mode: str, sudo_perf: bool) -> None:
    if perf_mode == "none":
        return

    if sys.platform != "linux":
        raise RuntimeError("Linux perf integration is only supported when this script runs on Linux.")

    perf_check = shutil.which("perf")
    if perf_check is None:
        raise RuntimeError("perf was requested, but the 'perf' executable was not found in PATH.")

    if sudo_perf and not running_as_root() and shutil.which("sudo") is None:
        raise RuntimeError("--sudo-perf was requested, but the 'sudo' executable was not found in PATH.")


def running_as_root() -> bool:
    return hasattr(os, "geteuid") and os.geteuid() == 0


def perf_executable() -> str:
    return shutil.which("perf") or "perf"


def perf_command_prefix(sudo_perf: bool, env: dict[str, str]) -> list[str]:
    if not sudo_perf or running_as_root():
        return [perf_executable()]

    command = ["sudo"]
    if env:
        preserved_env = ",".join(sorted(env))
        command.append(f"--preserve-env={preserved_env}")
    command.append(perf_executable())
    return command


def normalize_selected_schemes(raw_schemes: Sequence[str]) -> list[str]:
    if not raw_schemes:
        return []

    selected: list[str] = []
    for raw_value in raw_schemes:
        for raw_scheme in raw_value.split(","):
            scheme = raw_scheme.strip()
            if not scheme:
                continue

            key = scheme.replace("-", "_").lower()
            if key == "all":
                return []

            canonical = SCHEME_ALIASES.get(key)
            if canonical is None:
                allowed = ", ".join(SCHEME_ORDER)
                raise ValueError(f"Unknown scheme '{scheme}'. Supported values: {allowed}")

            if canonical not in selected:
                selected.append(canonical)

    return sorted(selected, key=SCHEME_ORDER.index)


def benchmark_env(selected_schemes: Sequence[str]) -> dict[str, str]:
    if not selected_schemes:
        return {}
    return {BENCH_SCHEMES_ENV_VAR: ",".join(selected_schemes)}


def clean_directory(path: Path) -> None:
    if path.exists():
        shutil.rmtree(path)
    path.mkdir(parents=True, exist_ok=True)


def run_benchmark(bench_name: str, env: dict[str, str]) -> None:
    run_command(["cargo", "bench", "--bench", bench_name], env=env)


def build_bench_binary(bench_name: str) -> Path:
    command = [
        "cargo",
        "bench",
        "--bench",
        bench_name,
        "--no-run",
        "--message-format=json",
    ]
    display = " ".join(shlex.quote(part) for part in command)
    print(f"[run] {display}")
    result = subprocess.run(
        command,
        cwd=REPO_ROOT,
        check=True,
        text=True,
        stdout=subprocess.PIPE,
    )

    bench_binary: Optional[Path] = None
    for line in result.stdout.splitlines():
        try:
            message = json.loads(line)
        except json.JSONDecodeError:
            continue

        if message.get("reason") != "compiler-artifact":
            continue
        target = message.get("target") or {}
        target_kinds = target.get("kind") or []
        if target.get("name") != bench_name or "bench" not in target_kinds:
            continue
        executable = message.get("executable")
        if executable:
            bench_binary = Path(executable)

    if bench_binary is None:
        raise RuntimeError(f"Could not determine the built executable for bench target '{bench_name}'.")

    if not bench_binary.exists():
        raise FileNotFoundError(f"Built bench executable not found: {bench_binary}")

    return bench_binary


def run_perf_stat(
    bench_binary: Path,
    perf_events: str,
    perf_output_dir: Path,
    env: dict[str, str],
    sudo_perf: bool,
) -> dict[str, str]:
    perf_command: list[Union[str, os.PathLike[str]]] = perf_command_prefix(sudo_perf, env)
    perf_command.append("stat")
    if perf_events:
        perf_command.extend(["-e", perf_events])

    perf_stat_path = perf_output_dir / "perf_stat.txt"
    perf_command.extend(["-d", "-d", "-d", "-o", perf_stat_path, bench_binary])
    run_command(perf_command, env=env)
    return {"perf_stat_path": str(perf_stat_path)}


def run_perf_record(
    bench_binary: Path,
    perf_events: str,
    perf_output_dir: Path,
    env: dict[str, str],
    sudo_perf: bool,
) -> dict[str, str]:
    perf_command: list[Union[str, os.PathLike[str]]] = perf_command_prefix(sudo_perf, env)
    perf_command.append("record")
    if perf_events:
        perf_command.extend(["-e", perf_events])

    perf_data_path = perf_output_dir / "perf.data"
    perf_report_path = perf_output_dir / "perf_report.txt"
    perf_command.extend(["-o", perf_data_path, bench_binary])
    run_command(perf_command, env=env)
    report_command = [perf_executable(), "report", "--stdio", "-i", os.fspath(perf_data_path)]
    display = " ".join(shlex.quote(part) for part in report_command)
    print(f"[run] {display}")
    report_result = subprocess.run(
        report_command,
        cwd=REPO_ROOT,
        check=True,
        text=True,
        stdout=subprocess.PIPE,
    )
    print(report_result.stdout, end="")
    perf_report_path.write_text(report_result.stdout, encoding="utf-8")
    return {
        "perf_data_path": str(perf_data_path),
        "perf_report_path": str(perf_report_path),
    }


def run_perf_benchmark(
    bench_name: str,
    perf_mode: str,
    perf_events: str,
    perf_output_dir: Path,
    env: dict[str, str],
    sudo_perf: bool,
) -> dict[str, str]:
    bench_binary = build_bench_binary(bench_name)
    clean_directory(perf_output_dir)

    metadata = {
        "bench_binary": str(bench_binary),
        "perf_mode": perf_mode,
        "sudo_perf": str(sudo_perf),
    }
    if perf_events:
        metadata["perf_events"] = perf_events

    if perf_mode in {"stat", "both"}:
        metadata.update(run_perf_stat(bench_binary, perf_events, perf_output_dir, env, sudo_perf))

    if perf_mode in {"record", "both"}:
        metadata.update(run_perf_record(bench_binary, perf_events, perf_output_dir, env, sudo_perf))

    return metadata


def run_plotter(
    python_executable: Path,
    criterion_root: Path,
    plot_output_dir: Path,
    group: str,
    selected_schemes: Sequence[str],
) -> None:
    plotter_path = PLOTTER_FILE_PATH
    if not plotter_path.exists():
        raise FileNotFoundError(f"Plotter script not found: {PLOTTER_FILE_PATH}")

    if not criterion_root.exists():
        raise FileNotFoundError(f"Criterion output directory not found: {criterion_root}")

    clean_directory(plot_output_dir)
    command: list[Union[str, os.PathLike[str]]] = [
        python_executable,
        plotter_path,
        "--criterion-root",
        criterion_root,
        "--output-dir",
        plot_output_dir,
        "--group",
        group,
    ]
    for scheme in selected_schemes:
        command.extend(["--scheme", scheme])

    run_command(command)


def collect_plot_files(plot_output_dir: Path) -> list[Path]:
    if not plot_output_dir.exists():
        raise FileNotFoundError(f"Plot output directory not found: {plot_output_dir}")

    plots = sorted(plot_output_dir.glob("*.png"))
    if not plots:
        raise RuntimeError(f"No plot PNG files found in {plot_output_dir}")
    return plots


def publish_plots(
    plot_output_dir: Path,
    publish_dir: Path,
    metadata: dict[str, str],
    timestamp: str,
) -> tuple[Path, Path]:
    runs_dir = publish_dir / "plots" / "runs"
    latest_dir = publish_dir / "plots" / "latest"
    run_dir = runs_dir / timestamp

    run_dir.parent.mkdir(parents=True, exist_ok=True)
    shutil.copytree(plot_output_dir, run_dir)

    if latest_dir.exists():
        shutil.rmtree(latest_dir)
    shutil.copytree(plot_output_dir, latest_dir)

    for target_dir in (run_dir, latest_dir):
        metadata_path = target_dir / "run_metadata.json"
        metadata_path.write_text(json.dumps(metadata, indent=2) + "\n", encoding="utf-8")

    return run_dir, latest_dir


def publish_perf_artifacts(
    perf_output_dir: Path,
    publish_dir: Path,
    metadata: dict[str, str],
    timestamp: str,
) -> tuple[Path, Path]:
    runs_dir = publish_dir / "perf" / "runs"
    latest_dir = publish_dir / "perf" / "latest"
    run_dir = runs_dir / timestamp

    run_dir.parent.mkdir(parents=True, exist_ok=True)
    shutil.copytree(perf_output_dir, run_dir)

    if latest_dir.exists():
        shutil.rmtree(latest_dir)
    shutil.copytree(perf_output_dir, latest_dir)

    for target_dir in (run_dir, latest_dir):
        metadata_path = target_dir / "run_metadata.json"
        metadata_path.write_text(json.dumps(metadata, indent=2) + "\n", encoding="utf-8")

    return run_dir, latest_dir


def main() -> int:
    args = parse_args()
    ensure_nix_dev_shell(args)

    criterion_root = resolve_repo_path(args.criterion_root)
    plot_output_dir = resolve_repo_path(args.plot_output_dir)
    perf_output_dir = resolve_repo_path(args.perf_output_dir)
    publish_dir = resolve_repo_path(args.publish_dir)
    python_executable = Path(sys.executable).resolve()
    selected_schemes = normalize_selected_schemes(args.scheme)
    selected_benchmark_env = benchmark_env(selected_schemes)
    timestamp = datetime.now().strftime("%Y%m%d_%H%M%S")

    python_version = verify_python_version()
    verify_python_dependencies(skip_plot=args.skip_plot)
    rustc_version, cargo_version = verify_rust_toolchain()
    verify_perf_support(args.perf, args.sudo_perf)

    print(
        "[info] Toolchain OK: "
        f"python={format_version(python_version)} "
        f"rustc={rustc_version} "
        f"cargo={cargo_version}"
    )

    perf_metadata: dict[str, str] = {}
    if not args.skip_bench:
        if args.perf == "none":
            run_benchmark(args.bench_name, selected_benchmark_env)
        else:
            perf_metadata = run_perf_benchmark(
                args.bench_name,
                args.perf,
                args.perf_events,
                perf_output_dir,
                selected_benchmark_env,
                args.sudo_perf,
            )

    if not args.skip_plot:
        run_plotter(
            python_executable,
            criterion_root,
            plot_output_dir,
            args.group,
            selected_schemes,
        )

    plots = collect_plot_files(plot_output_dir)
    metadata = {
        "generated_at": datetime.now().isoformat(timespec="seconds"),
        "repo_root": str(REPO_ROOT),
        "python_executable": str(python_executable),
        "python_version": format_version(python_version),
        "rustc_version": rustc_version,
        "cargo_version": cargo_version,
        "bench_name": args.bench_name,
        "selected_schemes": ",".join(selected_schemes) if selected_schemes else "all",
        "criterion_root": str(criterion_root),
        "plot_output_dir": str(plot_output_dir),
        "plot_count": str(len(plots)),
        "perf_mode": args.perf,
    }
    metadata.update(perf_metadata)
    run_dir, latest_dir = publish_plots(plot_output_dir, publish_dir, metadata, timestamp)

    print("[done] Published plots:")
    print(f"  latest: {latest_dir}")
    print(f"  archived: {run_dir}")
    if args.perf != "none" and perf_output_dir.exists():
        perf_run_dir, perf_latest_dir = publish_perf_artifacts(
            perf_output_dir,
            publish_dir,
            metadata,
            timestamp,
        )
        print("[done] Published perf artifacts:")
        print(f"  latest: {perf_latest_dir}")
        print(f"  archived: {perf_run_dir}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
