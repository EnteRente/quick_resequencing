#!/usr/bin/env python3

from __future__ import annotations

import argparse
import csv
import os
import re
from pathlib import Path
from statistics import median

cache_root = Path("target/.cache").resolve()
cache_root.mkdir(parents=True, exist_ok=True)
os.environ.setdefault("XDG_CACHE_HOME", str(cache_root))

matplotlib_cache = Path("target/.matplotlib").resolve()
matplotlib_cache.mkdir(parents=True, exist_ok=True)
os.environ.setdefault("MPLCONFIGDIR", str(matplotlib_cache))

import matplotlib

matplotlib.use("Agg")

import matplotlib.pyplot as plt
from matplotlib.lines import Line2D
from matplotlib.ticker import EngFormatter, MaxNLocator

RANDOM_LOSS_RATE_PACKET_COUNT = 10_000
RANDOM_LOSS_FOCUS_MAX_PACKET_COUNT = 60_000
PERF_COUNTER_IMPLEMENTATION_ORDER = ["s2n-quic", "linux_tcp", "quiche", "quic-go"]
IMPLEMENTATION_COLORS = {
    "linux_tcp": "#355070",
    "quic-go": "#ffbf00",
    "quiche": "#B56576",
    "s2n-quic": "#2A9D8F",
    "lsquic": "#E76F51",
}


def parse_args() -> argparse.Namespace:
    parser = argparse.ArgumentParser(
        description="Generate perf counter box plots from perf_counter_samples.csv."
    )
    parser.add_argument(
        "--input",
        type=Path,
        default=Path("target/perf_artifacts/perf_counter_samples.csv"),
        help="CSV file generated by run_benchmark_pipeline.py --perf-counter-boxplots.",
    )
    parser.add_argument(
        "--output-dir",
        type=Path,
        default=Path("target/perf_artifacts"),
        help="Directory where perf counter plot PDFs will be written.",
    )
    return parser.parse_args()


def safe_path_component(value: str) -> str:
    safe_value = re.sub(r"[^A-Za-z0-9_.-]+", "_", value).strip("_")
    if not safe_value:
        raise ValueError(f"Cannot derive a filesystem-safe name from: {value!r}")
    return safe_value


def implementation_sort_key(implementation: str) -> tuple[int, str]:
    if implementation in PERF_COUNTER_IMPLEMENTATION_ORDER:
        return (
            PERF_COUNTER_IMPLEMENTATION_ORDER.index(implementation),
            implementation,
        )
    return (len(PERF_COUNTER_IMPLEMENTATION_ORDER), implementation)


def perf_event_slug(event: str) -> str:
    return safe_path_component(event.replace("-", "_").replace(":", "_")).lower()


def perf_event_axis_label(event: str) -> str:
    labels = {
        "cycles": "CPU cycles per burst",
        "cache-misses": "Cache misses per burst",
    }
    return labels.get(event, f"{event} per burst")


def counter_value_per_burst(row: dict[str, str]) -> float:
    if row.get("count_per_burst"):
        return float(row["count_per_burst"])

    if row.get("raw_count") and row.get("timed_iterations"):
        timed_iterations = float(row["timed_iterations"])
        if timed_iterations <= 0.0:
            raise ValueError("timed_iterations must be greater than zero")
        return float(row["raw_count"]) / timed_iterations

    return float(row["count_per_packet"]) * float(row["packet_count"])


def read_rows(input_path: Path) -> list[dict[str, str]]:
    with input_path.open("r", encoding="utf-8", newline="") as handle:
        return list(csv.DictReader(handle))


def plot_perf_counter_boxplots(samples_csv: Path, output_dir: Path) -> list[Path]:
    rows = read_rows(samples_csv)
    if not rows:
        raise RuntimeError(f"No perf counter samples found in {samples_csv}")

    output_dir.mkdir(parents=True, exist_ok=True)
    plot_paths: list[Path] = []
    scenarios: list[tuple[str, str, str, int | None, str | None]] = [
        ("RandomLossRate", "Random loss rate", "Loss rate", None, None),
        ("RandomLoss", "Random loss", "Packet burst size", None, None),
        (
            "RandomLoss",
            "Random loss",
            "Packet burst size",
            RANDOM_LOSS_FOCUS_MAX_PACKET_COUNT,
            "random_loss_upto_60000",
        ),
    ]

    for scheme, title, x_label, max_packet_count, forced_slug in scenarios:
        scheme_rows = [row for row in rows if row["scheme"] == scheme]
        if max_packet_count is not None:
            scheme_rows = [
                row
                for row in scheme_rows
                if int(row["packet_count"]) <= max_packet_count
            ]
        if not scheme_rows:
            continue

        events = sorted({row["event"] for row in scheme_rows})
        implementations = sorted(
            {row["implementation"] for row in scheme_rows},
            key=implementation_sort_key,
        )
        if scheme == "RandomLossRate":
            x_values = sorted({int(row["loss_rate_percent"]) for row in scheme_rows})
            x_labels = {value: f"{value}%" for value in x_values}
            title_suffix = f"({RANDOM_LOSS_RATE_PACKET_COUNT:,}-packet burst)"
            slug = "random_loss_rate"
        else:
            x_values = sorted({int(row["packet_count"]) for row in scheme_rows})
            x_labels = {value: f"{value:,}" for value in x_values}
            if max_packet_count is None:
                title_suffix = "(1% loss probability)"
                slug = "random_loss"
            else:
                title_suffix = (
                    f"(1% loss probability, up to {max_packet_count:,} packets)"
                )
                slug = forced_slug or f"random_loss_upto_{max_packet_count}"

        x_positions = {value: index for index, value in enumerate(x_values)}
        implementation_count = len(implementations)
        midpoint = (implementation_count - 1) / 2.0
        offsets = {
            implementation: (index - midpoint) * 0.17
            for index, implementation in enumerate(implementations)
        }

        for event in events:
            fig, ax = plt.subplots(figsize=(max(10.0, 5.8 + len(x_values) * 0.8), 6.4))

            for implementation in implementations:
                datasets: list[list[float]] = []
                positions: list[float] = []
                trend_y: list[float] = []
                for x_value in x_values:
                    values = [
                        counter_value_per_burst(row)
                        for row in scheme_rows
                        if row["event"] == event
                        and row["implementation"] == implementation
                        and (
                            int(row["loss_rate_percent"]) == x_value
                            if scheme == "RandomLossRate"
                            else int(row["packet_count"]) == x_value
                        )
                    ]
                    if not values:
                        continue
                    datasets.append(values)
                    positions.append(x_positions[x_value] + offsets[implementation])
                    trend_y.append(median(values))

                if not datasets:
                    continue

                color = IMPLEMENTATION_COLORS.get(implementation, "#8D99AE")
                ax.boxplot(
                    datasets,
                    positions=positions,
                    widths=0.14,
                    vert=True,
                    patch_artist=True,
                    showfliers=False,
                    manage_ticks=False,
                    boxprops={
                        "facecolor": color,
                        "edgecolor": "#1F1F1F",
                        "linewidth": 1.8,
                        "alpha": 0.95,
                    },
                    whiskerprops={"color": "#1F1F1F", "linewidth": 1.8},
                    capprops={"color": "#1F1F1F", "linewidth": 1.8},
                    medianprops={"color": "#F7F7F7", "linewidth": 2.4},
                )
                ax.plot(
                    positions,
                    trend_y,
                    linestyle=":",
                    linewidth=1.15,
                    color=color,
                    alpha=0.75,
                    zorder=4,
                )

            fig.suptitle(
                f"{title} perf counters {title_suffix}",
                fontsize=15,
                x=0.08,
                y=0.985,
                ha="left",
            )
            ax.set_xlabel(x_label)
            ax.set_ylabel(perf_event_axis_label(event))
            ax.set_xticks([x_positions[value] for value in x_values])
            ax.set_xticklabels([x_labels[value] for value in x_values], fontsize=10)
            ax.yaxis.set_major_locator(MaxNLocator(nbins=6))
            ax.yaxis.set_major_formatter(EngFormatter())
            ax.grid(axis="y", which="major", linestyle=":", linewidth=0.7, alpha=0.45)
            ax.set_axisbelow(True)

            legend_handles = [
                Line2D(
                    [0],
                    [0],
                    color=IMPLEMENTATION_COLORS.get(implementation, "#8D99AE"),
                    marker="s",
                    linestyle=":",
                    linewidth=1.15,
                    markersize=8,
                    markerfacecolor=IMPLEMENTATION_COLORS.get(implementation, "#8D99AE"),
                    markeredgecolor="#1F1F1F",
                    label=implementation,
                )
                for implementation in implementations
            ]
            fig.legend(
                handles=legend_handles,
                loc="upper center",
                bbox_to_anchor=(0.56, 0.93),
                frameon=False,
                ncol=len(legend_handles),
                columnspacing=1.4,
                handletextpad=0.5,
            )
            fig.tight_layout(rect=(0.06, 0.08, 0.99, 0.86))

            output_path = output_dir / f"perf_{slug}_{perf_event_slug(event)}.pdf"
            fig.savefig(output_path, bbox_inches="tight")
            plt.close(fig)
            plot_paths.append(output_path)
            print(f"Wrote perf counter boxplot to {output_path}")

    return plot_paths


def main() -> int:
    args = parse_args()
    input_path = args.input.resolve()
    output_dir = args.output_dir.resolve()
    if not input_path.exists():
        raise FileNotFoundError(f"Perf counter sample CSV not found: {input_path}")

    plot_paths = plot_perf_counter_boxplots(input_path, output_dir)
    if not plot_paths:
        raise RuntimeError(f"No perf counter plots were generated from {input_path}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
