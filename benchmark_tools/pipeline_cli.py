"""Command-line interface for the benchmark pipeline."""

from __future__ import annotations

import argparse
import sys
from pathlib import Path
from typing import Sequence

from benchmark_tools.config import (
    DEFAULT_BENCHMARK_GROUP,
    DEFAULT_CRITERION_ROOT,
    DEFAULT_PERF_OUTPUT_DIR,
    DEFAULT_PLOT_OUTPUT_DIR,
    IMPLEMENTATION_ORDER,
    REPO_ROOT,
    SCHEME_ORDER,
)
from benchmark_tools.pipeline import PipelineConfig, run_pipeline
from benchmark_tools.toolchain import ensure_nix_dev_shell

BENCHMARK_RESULTS_DIR = REPO_ROOT / "benchmark_results"


def parse_args(argv: Sequence[str] | None = None) -> argparse.Namespace:
    parser = argparse.ArgumentParser(
        description=(
            "Enter the Nix dev shell when needed, verify the toolchain, run the "
            "Criterion benchmark, generate the box plots, and publish them to "
            f"{BENCHMARK_RESULTS_DIR} folder."
        )
    )
    parser.add_argument(
        "--bench-name",
        default="resequencing_bench",
        help="Cargo bench target to run.",
    )
    parser.add_argument(
        "--criterion-root",
        type=Path,
        default=DEFAULT_CRITERION_ROOT,
        help="Criterion output directory generated by cargo bench.",
    )
    parser.add_argument(
        "--plot-output-dir",
        type=Path,
        default=DEFAULT_PLOT_OUTPUT_DIR,
        help="Intermediate directory where Criterion plot PDFs are written.",
    )
    parser.add_argument(
        "--publish-dir",
        type=Path,
        default=Path("benchmark_results"),
        help="Stable repo-root folder where the generated plots are copied.",
    )
    parser.add_argument(
        "--group",
        default=DEFAULT_BENCHMARK_GROUP,
        help="Criterion benchmark group to plot.",
    )
    parser.add_argument(
        "--scheme",
        action="append",
        default=[],
        help=(
            "Only benchmark and plot the given scheme. Repeat this option or use a "
            f"comma-separated list. Supported values: {', '.join(SCHEME_ORDER)}."
        ),
    )
    parser.add_argument(
        "--perf",
        choices=["none", "stat", "record", "both"],
        default="none",
        help=(
            "Run the bench binary under Linux perf. 'stat' writes summary counters, "
            "'record' writes perf.data plus a text report, and 'both' runs each."
        ),
    )
    parser.add_argument(
        "--perf-events",
        action="append",
        default=[],
        nargs="+",
        metavar="EVENT",
        help=(
            "Optional perf event selector. Repeat this option, pass multiple "
            "space-separated events, or use comma-separated lists."
        ),
    )
    parser.add_argument(
        "--perf-by-implementation",
        action="store_true",
        help="Run perf separately for each receive-buffer implementation.",
    )
    parser.add_argument(
        "--perf-by-scenario",
        action="store_true",
        help="Run perf separately for each implementation, scheme, and burst size.",
    )
    parser.add_argument(
        "--perf-counter-boxplots",
        action="store_true",
        help=(
            "Collect repeated perf counter samples for RandomLoss and "
            "RandomLossRate and generate box plots."
        ),
    )
    parser.add_argument(
        "--perf-counter-samples",
        type=int,
        default=3,
        help="Number of repeated perf stat samples per box-plot data point.",
    )
    parser.add_argument(
        "--implementation",
        action="append",
        default=[],
        help=(
            "Only benchmark, plot, and run perf for the given implementation. "
            "Repeat this option or use a comma-separated list. Supported values: "
            f"{', '.join(IMPLEMENTATION_ORDER)}."
        ),
    )
    parser.add_argument(
        "--burst-size",
        "--packet-count",
        action="append",
        default=[],
        dest="packet_counts",
        help=(
            "Only benchmark, plot, and run perf for the given packet count/burst "
            "size. Repeat this option or use a comma-separated list. Use 'all' for "
            "the default full set."
        ),
    )
    parser.add_argument(
        "--sudo-perf",
        action="store_true",
        help=(
            "Prefix only perf stat/record/report commands with sudo; do not run the "
            "whole pipeline as root."
        ),
    )
    parser.add_argument(
        "--perf-output-dir",
        type=Path,
        default=DEFAULT_PERF_OUTPUT_DIR,
        help="Intermediate directory used for raw perf output before publishing.",
    )
    parser.add_argument(
        "--skip-bench",
        action="store_true",
        help="Skip cargo bench and only re-render plots from existing Criterion output.",
    )
    parser.add_argument(
        "--skip-plot",
        action="store_true",
        help="Skip plot generation and publish existing plot files.",
    )
    parser.add_argument(
        "--no-nix",
        action="store_true",
        help="Do not auto-enter the Nix dev shell; use the current environment as-is.",
    )
    return parser.parse_args(argv)


def main(argv: Sequence[str] | None = None) -> int:
    effective_argv = list(sys.argv[1:] if argv is None else argv)
    args = parse_args(effective_argv)
    ensure_nix_dev_shell(args.no_nix, effective_argv)
    return run_pipeline(PipelineConfig.from_namespace(args))


if __name__ == "__main__":
    raise SystemExit(main())
